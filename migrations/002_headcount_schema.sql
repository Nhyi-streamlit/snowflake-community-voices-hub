-- Event Headcount tab (Speaker Portal). Run in the SFDEVREL account, in the database/schema
-- set on the [connections.cv_headcount] secret. The service role needs USAGE on the
-- database/schema/warehouse, SNOWFLAKE.CORTEX_USER, plus the grants below.

CREATE TABLE IF NOT EXISTS HEADCOUNT_EVENTS (
    EVENT_ID STRING PRIMARY KEY,
    OWNER_EMAIL STRING NOT NULL,           -- verified Google email of the speaker
    EVENT_NAME STRING NOT NULL,
    EVENT_DATE DATE,
    LOCATION STRING,
    REPORTED_ATTENDANCE INT,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS HEADCOUNT_PHOTOS (
    PHOTO_ID STRING PRIMARY KEY,
    EVENT_ID STRING NOT NULL,
    FILE_PATH STRING,                      -- <event_id>/<photo_id>.jpg in HEADCOUNT_PHOTOS stage
    FILE_NAME STRING,
    PEOPLE_COUNT INT,
    MANUAL_COUNT INT,
    CONFIDENCE STRING,
    NOTES STRING,
    MODEL STRING,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Server-side encryption is required for AI_COMPLETE to read staged images.
CREATE STAGE IF NOT EXISTS HEADCOUNT_PHOTOS
    DIRECTORY = (ENABLE = TRUE)
    ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE');

