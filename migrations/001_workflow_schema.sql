-- 001_workflow_schema.sql — Community Voices workflow store.
-- Run with scripts/migrate.py, which sets the target schema first (USE SCHEMA <db>.<schema>).
-- Hybrid tables enforce PRIMARY KEY / UNIQUE, which is what makes idempotency real.
-- Idempotent: safe to re-run.

CREATE HYBRID TABLE IF NOT EXISTS WF_EVENTS (
    EVENT_ID        VARCHAR(64)  PRIMARY KEY,
    NAME            VARCHAR(500) NOT NULL,
    STATUS          VARCHAR(20)  NOT NULL,
    START_DATE      DATE,
    CITY            VARCHAR(200),
    LEGACY_EVENT_ID VARCHAR(64),
    CREATED_BY      VARCHAR(256),
    CREATED_AT      TIMESTAMP_NTZ NOT NULL,
    UNIQUE (LEGACY_EVENT_ID)
);

CREATE HYBRID TABLE IF NOT EXISTS WF_MEMBERS (
    MEMBER_ID          VARCHAR(64)  PRIMARY KEY,
    EVENT_ID           VARCHAR(64)  NOT NULL,
    ROLE               VARCHAR(20)  NOT NULL,
    EMAIL              VARCHAR(320) NOT NULL,
    STATUS             VARCHAR(20)  NOT NULL,
    SUBJECT            VARCHAR(256),
    DISPLAY_NAME       VARCHAR(300),
    SLACK_USER_ID      VARCHAR(64),
    SHARED_WITH_VENDOR BOOLEAN DEFAULT FALSE,
    CREATED_BY         VARCHAR(256),
    CREATED_AT         TIMESTAMP_NTZ NOT NULL,
    BOUND_AT           TIMESTAMP_NTZ,
    UNIQUE (EVENT_ID, ROLE, EMAIL),
    INDEX IX_MEMBERS_SUBJECT (SUBJECT),
    INDEX IX_MEMBERS_EMAIL (EMAIL),
    INDEX IX_MEMBERS_EVENT (EVENT_ID)
);

CREATE HYBRID TABLE IF NOT EXISTS WF_ITEMS (
    ITEM_ID            VARCHAR(64) PRIMARY KEY,
    EVENT_ID           VARCHAR(64) NOT NULL,
    ITEM_TYPE          VARCHAR(40) NOT NULL,
    PARTY              VARCHAR(20) NOT NULL,
    TITLE              VARCHAR(300) NOT NULL,
    STATUS             VARCHAR(30) NOT NULL,
    DUE_DATE           DATE,
    ASSIGNEE_MEMBER_ID VARCHAR(64),
    VENDOR_VISIBLE     BOOLEAN DEFAULT FALSE,
    SPEAKER_ACTION     BOOLEAN DEFAULT FALSE,
    CURRENT_VERSION    NUMBER(10) NOT NULL DEFAULT 0,
    APPROVED_VERSION   NUMBER(10) NOT NULL DEFAULT 0,
    UPDATED_AT         TIMESTAMP_NTZ,
    INDEX IX_ITEMS_EVENT (EVENT_ID)
);

-- Append-only: every upload or text revision is a new row. Nothing is overwritten.
CREATE HYBRID TABLE IF NOT EXISTS WF_ITEM_VERSIONS (
    ITEM_ID         VARCHAR(64) NOT NULL,
    VERSION         NUMBER(10)  NOT NULL,
    SUBMITTED_BY    VARCHAR(256) NOT NULL,
    SUBMITTED_ROLE  VARCHAR(20) NOT NULL,
    SUBMITTED_AT    TIMESTAMP_NTZ NOT NULL,
    CONTENT_SHA256  VARCHAR(64) NOT NULL,
    ACTION_KEY      VARCHAR(64) NOT NULL,
    TEXT_JSON       VARCHAR(65536),
    FILE_PATH       VARCHAR(1000),
    FILE_NAME       VARCHAR(500),
    FILE_SHA256     VARCHAR(64),
    FILE_SIZE       NUMBER(18),
    PRIMARY KEY (ITEM_ID, VERSION),
    UNIQUE (ACTION_KEY)
);

CREATE HYBRID TABLE IF NOT EXISTS WF_AUDIT (
    AUDIT_ID      VARCHAR(64) PRIMARY KEY,
    ACTION_KEY    VARCHAR(64) NOT NULL,
    EVENT_ID      VARCHAR(64) NOT NULL,
    ACTION        VARCHAR(40) NOT NULL,
    ACTOR_SUBJECT VARCHAR(256) NOT NULL,
    ACTOR_ROLE    VARCHAR(20) NOT NULL,
    CREATED_AT    TIMESTAMP_NTZ NOT NULL,
    ITEM_ID       VARCHAR(64),
    FROM_STATUS   VARCHAR(30),
    TO_STATUS     VARCHAR(30),
    NOTE          VARCHAR(4000),
    UNIQUE (ACTION_KEY),
    INDEX IX_AUDIT_EVENT (EVENT_ID)
);

CREATE HYBRID TABLE IF NOT EXISTS WF_OUTBOX (
    NOTIFICATION_ID     VARCHAR(64) PRIMARY KEY,   -- idempotency key
    ACTION_KEY          VARCHAR(64) NOT NULL,
    EVENT_ID            VARCHAR(64) NOT NULL,
    RULE                VARCHAR(60) NOT NULL,
    CHANNEL             VARCHAR(10) NOT NULL,
    STATUS              VARCHAR(20) NOT NULL,
    CREATED_AT          TIMESTAMP_NTZ NOT NULL,
    NEXT_ATTEMPT_AT     TIMESTAMP_NTZ NOT NULL,
    ITEM_ID             VARCHAR(64),
    RECIPIENT_MEMBER_ID VARCHAR(64),
    RECIPIENT_ROLE      VARCHAR(20),
    ADDRESS             VARCHAR(320),
    SUBJECT             VARCHAR(500),
    BODY                VARCHAR(8000),
    LINK                VARCHAR(1000),
    DEADLINE            DATE,
    ATTEMPTS            NUMBER(5) NOT NULL DEFAULT 0,
    MAX_ATTEMPTS        NUMBER(5) NOT NULL DEFAULT 5,
    LAST_ERROR          VARCHAR(500),
    PROVIDER_MESSAGE_ID VARCHAR(256),
    CLAIM_TOKEN         VARCHAR(64),
    UPDATED_AT          TIMESTAMP_NTZ,
    INDEX IX_OUTBOX_STATUS (STATUS),
    INDEX IX_OUTBOX_ACTION (ACTION_KEY)
);

-- Private files. No directory table, no presigned URLs: the app streams files after authorization.
CREATE STAGE IF NOT EXISTS WF_FILES
    ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE')
    COMMENT = 'Community Voices private uploads';
